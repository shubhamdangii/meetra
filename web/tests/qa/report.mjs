// Reads the Playwright JSON reports and writes TESTING.md (checklist, ticked only with evidence) and test-results/qa/baseline.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const web = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const root = path.resolve(web, "..");
const res = (f) => path.join(web, "test-results", f);
const features = JSON.parse(fs.readFileSync(path.join(web, "tests/qa/features.json"), "utf8"));
const load = (f) => (fs.existsSync(res(f)) ? JSON.parse(fs.readFileSync(res(f), "utf8")) : null);

/** Flatten a Playwright JSON report into one row per (test x project). */
function flatten(report, suite) {
  const rows = [];
  const walk = (node, titles) => {
    const t = node.title && !/\.(spec|setup)\.ts$/.test(node.title) ? [...titles, node.title] : titles;
    for (const sp of node.specs ?? []) for (const tc of sp.tests ?? []) {
      const last = tc.results?.[tc.results.length - 1];
      const status = tc.status === "expected" ? "passed" : tc.status === "skipped" ? "skipped" : tc.status === "flaky" ? "flaky" : "failed";
      const err = last?.error?.message?.replace(/\u001b\[[0-9;]*m/g, "").split("\n").find((l) => l.trim()) ?? "";
      const shot = (last?.attachments ?? []).find((a) => a.name === "screenshot")?.path;
      rows.push({ suite, file: sp.file, title: [...t, sp.title].join(" > "), project: tc.projectName, status, err: err.slice(0, 220), shot, ran: !!last });
    }
    for (const s of node.suites ?? []) walk(s, t);
  };
  for (const s of report?.suites ?? []) walk(s, []);
  return rows;
}
const qa = flatten(load("qa-report.json") ?? load("qa/report.json"), "qa").filter((r) => !/auth\.setup/.test(r.file));
const e2e = flatten(load("e2e-report.json"), "e2e");
const smoke = flatten(load("smoke-report.json"), "smoke");
const all = [...qa, ...e2e, ...smoke];
const steps = (() => { try { return JSON.parse(fs.readFileSync(res("qa-steps.json"), "utf8")); } catch { return []; } })();

const count = (rows) => ({ passed: rows.filter((r) => r.status === "passed" || r.status === "flaky").length, failed: rows.filter((r) => r.status === "failed").length, skipped: rows.filter((r) => r.status === "skipped").length });
const findingFor = (row) => features.findings.find((f) => new RegExp(f.match, "i").test(`${row.file} > ${row.title}`));

// ---- per feature ----
const lines = features.features.map((f) => {
  const rows = all.filter((r) => (f.suite ? r.suite === f.suite : true) && new RegExp(f.match, "i").test(`${r.file} > ${r.title}`));
  const failed = rows.filter((r) => r.status === "failed"), ran = rows.filter((r) => r.status === "passed" || r.status === "flaky");
  let result, evidence;
  if (f.notTested) { result = "NOT TESTED"; evidence = f.notTested; }
  else if (!rows.length) { result = "NOT TESTED"; evidence = "no test yet"; }
  else if (failed.length) {
    result = "FAIL";
    const fd = findingFor(failed[0]);
    evidence = `${fd ? fd.id + ": " : ""}${[...new Set(failed.map((r) => r.project))].join(", ")} | ${failed[0].err}`;
  } else if (!ran.length && rows.every((r) => r.status === "skipped")) { result = "NOT TESTED"; evidence = "skipped on purpose: the flow notifies every other main admin (real people) on the live project"; }
  else if (!ran.length) { result = "BLOCKED"; evidence = "did not run (an earlier step failed or the device does not apply)"; }
  else { result = "PASS"; evidence = `${ran.length} run(s) on ${[...new Set(ran.map((r) => r.project))].join(", ")}: ${[...new Set(ran.map((r) => r.title.split(" > ").pop()))].slice(0, 2).join("; ")}`; }
  const skippedBlocked = rows.filter((r) => r.status === "skipped").length;
  return { ...f, result, evidence, failed, rows, skippedBlocked };
});

const ts = new Date().toISOString().replace("T", " ").slice(0, 16) + " UTC";
const tick = (r) => (r === "PASS" ? "[x]" : "[ ]");
const areas = [...new Set(features.features.map((f) => f.area))];

// ---- TESTING.md ----
let md = `# TESTING.md\n\nChecklist of every feature x role. An item is ticked ONLY when its tests passed in the last run (evidence shown). Unticked = failed, blocked or not tested.\nGenerated by \`npm run qa\` (the /qa command). Last run: ${ts}\n\n`;
md += `Run everything: \`npm --prefix web run qa\`  |  Seed only: \`npm --prefix web run qa:seed\`  |  Remove QA data: \`npm --prefix web run qa:reset\`\n\n`;
md += `Test environment: a local copy of the site (http://localhost:3100/meetra/) built from the current code and talking to the one live Supabase project. All test data is QA_ data (events, host) or qa-*@example.invalid accounts; the seed and reset refuse any other URL and delete only that data. Flows that would notify real people (other main admins) are NOT run and are listed as NOT TESTED.\n\n`;
for (const a of areas) {
  md += `## ${a}\n\n`;
  for (const f of lines.filter((l) => l.area === a)) md += `- ${tick(f.result)} ${f.feature} _(${f.role})_ - **${f.result}**: ${f.evidence}\n`;
  md += "\n";
}
md += `## Findings (fixed in the repo)\n\nBUG-1 and BUG-2 are fixed by migrations 20261128040000 and 20261128050000 (applied to live on 2026-11-28). BUG-3 is fixed in EventPage.tsx. Their tests above now pass. Original reports:\n\n` + features.findings.map((f) => `- **${f.id} (${f.kind})**: ${f.title}. ${f.note}`).join("\n") + "\n\n";
md += `## Cannot be tested\n\n` + features.cannotTest.map((c) => `- [ ] ${c.feature}: ${c.why}`).join("\n") + "\n";
fs.writeFileSync(path.join(root, "TESTING.md"), md);

// ---- baseline.md ----
const tot = count(all);
let b = `# QA baseline report\n\nRun: ${ts}. Environment: local site (localhost:3100) on the live project with QA_ data only.\n\n`;
b += `## Totals\n\n| Suite | Passed | Failed | Did not run / skipped |\n|---|---|---|---|\n`;
for (const [n, rows] of [["Role + lifecycle (3 devices)", qa], ["Old public tests on the QA site", e2e], ["Deployed-site smoke test", smoke]]) { const c = count(rows); b += `| ${n} | ${c.passed} | ${c.failed} | ${c.skipped} |\n`; }
b += `| **All** | **${tot.passed}** | **${tot.failed}** | **${tot.skipped}** |\n\n`;
if (steps.length) b += `Run steps: ${steps.map((s) => `${s.ok ? "ok" : "FAILED"} - ${s.name}`).join("; ")}\n\n`;
b += `## Results by feature\n\n| Feature | Role | Pass/Fail | Evidence |\n|---|---|---|---|\n`;
for (const f of lines) b += `| ${f.feature} | ${f.role} | ${f.result} | ${f.evidence.replace(/\|/g, "/")} |\n`;

const grouped = { "REAL BUG": [], "TEST PROBLEM": [], "DATA PROBLEM": [], UNCLASSIFIED: [] };
const seen = new Set();
for (const r of all.filter((x) => x.status === "failed")) {
  const fd = findingFor(r); const key = fd ? fd.id : r.title;
  if (seen.has(key)) continue; seen.add(key);
  (grouped[fd?.kind ?? "UNCLASSIFIED"] ??= []).push(fd ? `**${fd.id}** ${fd.title}. ${fd.note}` : `${r.title} [${r.project}] - ${r.err}`);
}
b += `\n## Failures, grouped\n\n`;
for (const [k, v] of Object.entries(grouped)) { b += `### ${k}\n\n` + (v.length ? v.map((x) => `- ${x}`).join("\n") : "- none") + "\n\n"; }
const blocked = lines.filter((l) => l.result === "BLOCKED" || l.result === "NOT TESTED");
b += `## Not tested\n\nBlocked or not run:\n` + (blocked.length ? blocked.map((l) => `- ${l.feature} (${l.role}): ${l.result} - ${l.evidence}`).join("\n") : "- none") + "\n\nCannot be tested:\n" + features.cannotTest.map((c) => `- ${c.feature}: ${c.why}`).join("\n") + "\n";
const shots = all.filter((r) => r.status === "failed" && r.shot).slice(0, 12).map((r) => `- ${path.relative(root, r.shot)} (${r.project}: ${r.title.split(" > ").pop()})`);
b += `\n## Failure screenshots\n\n${shots.join("\n") || "- none"}\n`;
fs.mkdirSync(res("qa"), { recursive: true });
fs.writeFileSync(res("qa/baseline.md"), b);
console.log(`TESTING.md and baseline written. passed ${tot.passed}, failed ${tot.failed}, skipped ${tot.skipped}`);
